import { recipeCatalog } from '@genovault/shared'
import { Hono } from 'hono'

/**
 * Каталог рецептів і словники згоди (`FR-005`, `FR-011`) — `T035`.
 *
 * # Чому без автентифікації
 *
 * Тут немає нічого, чого не видно з тексту програми: назви типів
 * використання, категорій покупців і параметри єдиного рецепта. Замок на
 * цьому маршруті приховав би не дані, а форму продукту — і власник, який ще не
 * увійшов, не побачив би, на що взагалі можна дати згоду.
 *
 * # Чому без залежностей
 *
 * Каталог — константи `packages/shared`, і цей маршрут не питає ані мережу,
 * ані сховище. Тому він і не вміє відповідати 503: рецепт, якого немає в
 * `RECIPES`, не існує ніде — ані в квоті, ані в диспетчері, — і саме це робить
 * список правдивим без жодного джерела, з яким він міг би розійтись.
 */
export function recipeRoutes() {
  const routes = new Hono()

  routes.get('/recipes', (c) => c.json(recipeCatalog()))

  return routes
}
