import { x25519 } from '@noble/curves/ed25519'

/**
 * Ключ, яким покупець читає звіт свого прогону (`T029`).
 *
 * # Чому він не зберігається ніде
 *
 * MPC шифрує звіт на `Run.buyer_x25519`, і без приватної половини звіт не
 * прочитає ніхто — включно з нами й із самим покупцем. Це ставить питання, де
 * ця половина живе. Продуктове рішення (2026-09-07): **ніде**. Вона щоразу
 * виводиться заново з підпису гаманця, тобто з того самого ключа, яким покупець
 * і платив за прогін.
 *
 * Ціна відома й названа: ще один підпис у шляху покупця, і відновлення працює
 * рівно доти, доки гаманець підписує детерміновано. Ed25519 у Solana такий за
 * стандартом (RFC 8032), і вбудований гаманець Privy його тримає; гаманець,
 * який додав би до підпису випадковість, зробив би старі звіти нечитними — і це
 * та властивість, яку треба перевірити на живому Privy, а не припустити.
 *
 * Альтернативу — секрет у `localStorage` — відкинуто: інший браузер, режим
 * інкогніто або чищення сайту, і звіт, за який заплачено, не прочитає вже
 * ніхто й ніколи.
 *
 * # Чому крива береться не з клієнта Arcium
 *
 * `@arcium-hq/client` реекспортує той самий `x25519` з `@noble/curves`, але сам
 * імпортує вузлівський `crypto` першим рядком (`randomBytes`, `createHash`,
 * `createCipheriv`) — і тому **не збирається під браузер** без полізаповнювача.
 * Виведення ключа звіту цього клієнта не потребує взагалі, тож воно бере криву
 * напряму: інакше екран замовлення тягнув би за собою шифр датасету разом із
 * його проблемою збірки.
 *
 * Сама проблема нікуди не зникла: `encryptDataset` (`T014`) без Arcium не
 * працює, а шифрувати датасет має саме браузер. Це відкрите питання до `T066`.
 *
 * # Чому ключ на кожен прогін свій
 *
 * У повідомлення входить нонс прогону, тож два прогони того самого покупця
 * шифруються на різні ключі. Спільний ключ на всі прогони означав би, що
 * витік однієї приватної половини відкриває всі звіти, які покупець колись
 * замовляв, — і минулі теж.
 */

export interface ReportKeypair {
  /** Приватна половина. Живе рівно стільки, скільки потрібно на розшифрування. */
  secretKey: Uint8Array
  /** Публічна половина — вона лягає в `Run.buyer_x25519` і стає публічною. */
  publicKey: Uint8Array
}

/**
 * Текст, який підписує гаманець.
 *
 * Домен на початку — не формальність: гаманець підписує ці байти наосліп, і
 * повідомлення без назви застосунку той самий підпис зробив би придатним для
 * чужого сайту, який попросив підписати те саме. Адреса покупця й нонс входять
 * у текст, щоб підпис не переносився ні на інший гаманець, ні на інший прогін.
 */
export function reportKeyMessage(buyer: string, nonce: bigint): string {
  return [
    'GenoVault: ключ для читання звіту прогону.',
    'Підпис не переказує коштів і нічого не змінює в мережі.',
    `buyer: ${buyer}`,
    `run nonce: ${nonce.toString(10)}`,
  ].join('\n')
}

/** Домен виведення. Змінити його — зробити всі раніше замовлені звіти нечитними. */
const HKDF_INFO = 'genovault/report-key/v1'

/**
 * Підпис гаманця → пара x25519.
 *
 * HKDF, а не sha256 від підпису: підпис Ed25519 — це не рівномірний ключовий
 * матеріал, а пара точок кривої, і брати від нього хеш «бо 32 байти» означає
 * покладатися на те, що так вийде добре. `info` тут прив'язує виведення до
 * версії: якщо колись доведеться змінити схему, старі ключі лишаться
 * обчислюваними за старим `info`, а не зникнуть.
 */
export async function deriveReportKey(signature: Uint8Array): Promise<ReportKeypair> {
  if (signature.length === 0) {
    throw new RangeError('підпис порожній — виводити ключ немає з чого')
  }

  // Копія, а не сам масив: `Uint8Array` над `SharedArrayBuffer` не є
  // `BufferSource` для WebCrypto, і без копії той самий код збирається в
  // `packages/crypto` й не збирається в `apps/web`, де підключений lib DOM.
  const material = await crypto.subtle.importKey('raw', new Uint8Array(signature), 'HKDF', false, [
    'deriveBits',
  ])
  const bits = await crypto.subtle.deriveBits(
    {
      name: 'HKDF',
      hash: 'SHA-256',
      // Солі немає навмисно: другого джерела ентропії тут не буває, а
      // випадкова сіль зробила б ключ невідновлюваним — тобто зламала б рівно
      // ту властивість, заради якої він і виводиться.
      salt: new Uint8Array(0),
      info: new TextEncoder().encode(HKDF_INFO),
    },
    material,
    256,
  )

  const secretKey = new Uint8Array(bits)
  return { secretKey, publicKey: x25519.getPublicKey(secretKey) }
}

/** 32 байти → шістнадцятковий рядок, у якому їх приймає `POST /runs`. */
export function toHex(bytes: Uint8Array): string {
  let hex = ''
  for (const byte of bytes) hex += byte.toString(16).padStart(2, '0')
  return hex
}
