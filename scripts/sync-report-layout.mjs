#!/usr/bin/env node
// Mirror of the report layout for `packages/shared` (the buyer's report on the run page).
//
//   node scripts/sync-report-layout.mjs          # rewrite from build/circuits.ts
//   node scripts/sync-report-layout.mjs --check  # compare, write nothing (gate)
//
// Why a mirror and not the compiler output itself: `build/` is not in git
// (`scripts/wsl-build-circuits.sh` restores it), so the browser bundle and CI
// cannot import it. The order and width of the report fields are the
// compiler's decision, not ours — a hand-written list would put numbers on the
// buyer's screen whose origin nobody checked. So the list is generated from
// `arcium build` output and compared with it in every gate that can see it.
//
// `--check` without `build/circuits.ts` skips only that comparison and says
// so; the checks that need nothing but the generated file still run.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(REPO, 'build/circuits.ts')
const OUT = join(REPO, 'packages/shared/src/report-layout.generated.ts')

const check = process.argv.slice(2).includes('--check')

function die(message) {
  console.error(`sync-report-layout: ${message}`)
  process.exit(1)
}

/** The `Report` packer of the compiler output: field names and the one width. */
function parseLayout(text) {
  const block = /Report:\s*createPacker<[^>]*>\(\s*\[([\s\S]*?)\]\s*as const,\s*'Report'\s*\)/.exec(
    text,
  )
  if (block === null) die(`${relative(REPO, SOURCE)} has no Report packer — not arcium build output`)
  const body = block[1]

  const entry =
    /\{\s*name:\s*'([^']+)',\s*type:\s*\{\s*Integer:\s*\{\s*signed:\s*(true|false),\s*width:\s*(\d+)\s*\}\s*\}\s*\}/g
  const fields = [...body.matchAll(entry)].map((match) => ({
    name: match[1],
    signed: match[2] === 'true',
    width: Number(match[3]),
  }))

  // Counted apart from what was parsed: a field of another shape must be a
  // named refusal, not a silent shift of every number after it.
  const declared = (body.match(/name:/g) ?? []).length
  if (fields.length !== declared) {
    die(`the Report packer declares ${declared} fields, ${fields.length} of a known shape`)
  }
  if (fields.length === 0) die('the Report packer is empty')
  const width = fields[0].width
  if (fields.some((field) => field.width !== width || field.signed)) {
    die('the Report packer mixes widths or signed fields — the reader cannot do that')
  }
  return { width, names: fields.map((field) => field.name) }
}

function render(layout) {
  const names = layout.names.map((name) => `    '${name}',`).join('\n')
  return `// Generated by scripts/sync-report-layout.mjs from build/circuits.ts — do not edit.

/** Field order and width of \`Report\` as \`arcium build\` packs it (\`frequencies_reveal\`). */
export const REPORT_LAYOUT = {
  width: ${layout.width},
  names: [
${names}
  ],
} as const
`
}

function readGenerated() {
  if (!existsSync(OUT)) return null
  const text = readFileSync(OUT, 'utf8')
  const width = /width:\s*(\d+)/.exec(text)
  const names = [...text.matchAll(/^\s{4}'([^']+)',$/gm)].map((match) => match[1])
  return { text, width: width === null ? null : Number(width[1]), names }
}

const haveSource = existsSync(SOURCE)

if (!check) {
  if (!haveSource) die(`${relative(REPO, SOURCE)} is missing — run scripts/wsl-build-circuits.sh first`)
  const layout = parseLayout(readFileSync(SOURCE, 'utf8'))
  writeFileSync(OUT, render(layout), { encoding: 'utf8' })
  console.log(`sync-report-layout: ${layout.names.length} fields × ${layout.width} bits → ${relative(REPO, OUT)}`)
  process.exit(0)
}

const generated = readGenerated()
if (generated === null) die(`${relative(REPO, OUT)} is missing — run without --check`)
if (generated.names.length === 0 || generated.width === null) {
  die(`${relative(REPO, OUT)} does not read as a layout`)
}

if (!haveSource) {
  console.log(
    `sync-report-layout: ${relative(REPO, SOURCE)} not here — compared nothing with the compiler, ` +
      `${generated.names.length} fields in the mirror`,
  )
  process.exit(0)
}

const expected = render(parseLayout(readFileSync(SOURCE, 'utf8')))
if (generated.text.replaceAll('\r\n', '\n') !== expected) {
  die(`${relative(REPO, OUT)} differs from ${relative(REPO, SOURCE)} — run without --check`)
}
console.log(`sync-report-layout: ${generated.names.length} fields × ${generated.width} bits match the compiler`)
