use anchor_lang::prelude::*;

/// Стеля комісії платформи — 10%.
///
/// `FR-019` вимагає, щоб розмір комісії був публічним і фіксованим на момент
/// замовлення. Публічність дає сам PDA, фіксацію — копія `fee_bps` у `Run`
/// (`T024`). Але сама по собі пара не заважає оператору підняти комісію до
/// 100% для наступних прогонів, тож межа перевіряється програмою, а не
/// репутацією оператора.
pub const MAX_FEE_BPS: u16 = 1_000;

/// Знаменник базисних пунктів: 10 000 bps = 100%.
pub const BPS_DENOMINATOR: u64 = 10_000;

/// Конфігурація платформи — єдиний акаунт на всю програму.
///
/// Seeds: `["config"]`. Без `authority` тут не було б кому оновлювати
/// комісію й ставити систему на паузу; без `mint` розрахунки не мали б
/// спільної валюти, і кожен прогін міг би бути в іншому токені.
#[account]
#[derive(InitSpace)]
pub struct PlatformConfig {
    /// Хто має право змінювати цю конфігурацію.
    pub authority: Pubkey,
    /// Мінт, у якому йдуть депозити, нарахування й комісія.
    pub mint: Pubkey,
    /// Комісія платформи в базисних пунктах.
    pub fee_bps: u16,
    /// Пауза: нові прогони не приймаються. Уже прийняті доводяться до кінця —
    /// інакше пауза стала б способом не платити власникам за виконану роботу.
    pub paused: bool,
    pub bump: u8,
}

impl PlatformConfig {
    pub const SEED: &'static [u8] = b"config";

    /// Сейф платформи — один токен-акаунт на всі депозити.
    ///
    /// Один спільний, а не по акаунту на прогін: розподіл між власниками стає
    /// суто бухгалтерією (`OwnerBalance`), і 50 нарахувань не тягнуть за собою
    /// 50 переказів. Токени рухаються рівно двічі — внесок покупця й виведення
    /// власника, — і саме тому `SC-007` (розподіл між 50 власниками < 30 с)
    /// досяжний без порційної петлі переказів.
    ///
    /// Ціна рішення названа: у сейфі лежать гроші всіх прогонів разом, тож
    /// «скільки саме належить цьому прогону» читається з `Run.escrow_amount`,
    /// а не з балансу акаунта. Сходження цих двох чисел доводить `SC-006`.
    pub const VAULT_SEED: &'static [u8] = b"vault";
}
